// A plain chat with a small language model running on this computer (Ollama, qwen3:1.7b), on Inventory and Studio.
// It sees only this conversation — not the building model, the selection or the screen — and changes nothing in
// the viewer. Its answers are generated: they can be wrong, and nothing in them comes from the IFC unless you put it
// into the conversation. Ollama is reached through Vite's proxy at /ollama (vite.config.ts).
import { h } from "./dom";

export const MODEL = "qwen3:1.7b";
const SYSTEM =
  "You are a helpful assistant in a university course on recovering and reusing building components. Answer briefly. " +
  "You do not see the building model, the user's screen or any data unless the user writes it here; say so when asked about them.";

interface Message {
  role: "system" | "user" | "assistant";
  content: string;
}

const $ = <T extends HTMLElement = HTMLElement>(id: string) => document.getElementById(id) as T;
let messages: Message[] = [];
let busy = false;

function setStatus(text: string, state: "ok" | "busy" | "bad", title = ""): void {
  const chip = $("chat-status");
  chip.replaceChildren(h("span", { class: `dot ${state}` }), h("span", { class: "text" }, text));
  chip.title = title;
}

/** Is Ollama running, and is the model installed? */
async function checkModel(): Promise<void> {
  try {
    const r = await fetch("/ollama/api/tags", { cache: "no-store" });
    const names: string[] = r.ok ? ((await r.json()).models ?? []).map((m: { name: string }) => m.name) : [];
    if (!r.ok) setStatus("Ollama not running", "bad", "Install Ollama (ollama.com) and start it.");
    else if (names.includes(MODEL)) setStatus(MODEL, "ok", `${MODEL} on this computer (Ollama)`);
    else setStatus(`${MODEL} missing`, "bad", `In a terminal: ollama pull ${MODEL}`);
  } catch {
    setStatus("Ollama not running", "bad", "Install Ollama (ollama.com) and start it.");
  }
}

function render(): void {
  const log = $("chat-log");
  if (!messages.length) {
    log.replaceChildren(h("li", { class: "chat-empty" },
      h("p", {}, `Ask ${MODEL} anything. It sees only this conversation, not the model or the screen.`),
      h("p", {}, "Its answers are generated and can be wrong.")));
    return;
  }
  log.replaceChildren(...messages.map((m) => m.role === "user"
    ? h("li", { class: "bubble user" }, m.content)
    : h("li", { class: `bubble assistant${m.content ? "" : " pending"}` },
      h("div", { class: "text" }, m.content || "…"),
      h("div", { class: "meta" }, h("span", {}, `generated by ${MODEL} · not from the IFC`)))));
  log.lastElementChild?.scrollIntoView({ block: "end" });
}

/** Ollama streams one JSON object per line; qwen3 may wrap its reasoning in <think>…</think>, which is not shown. */
async function ask(): Promise<void> {
  const reply: Message = { role: "assistant", content: "" };
  messages.push(reply);
  render();
  const res = await fetch("/ollama/api/chat", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ model: MODEL, stream: true, think: false,
      messages: [{ role: "system", content: SYSTEM }, ...messages.slice(0, -1)] }),
  });
  if (!res.ok || !res.body) throw new Error(`Ollama answered ${res.status}: ${await res.text()}`);
  const reader = res.body.getReader();
  const decoder = new TextDecoder();
  let buffer = "";
  let raw = "";
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    const lines = buffer.split("\n");
    buffer = lines.pop() ?? "";
    for (const line of lines.filter((l) => l.trim())) {
      const chunk = JSON.parse(line);
      if (chunk.error) throw new Error(chunk.error);
      raw += chunk.message?.content ?? "";
    }
    reply.content = raw.replace(/<think>[\s\S]*?(<\/think>|$)/g, "").trim();
    render();
  }
}

async function submit(ev: Event): Promise<void> {
  ev.preventDefault();
  const input = $<HTMLTextAreaElement>("chat-input");
  const text = input.value.trim();
  if (!text || busy) return;
  busy = true;
  input.value = "";
  messages.push({ role: "user", content: text });
  try {
    await ask();
  } catch (e) {
    messages = messages.filter((m) => m.content); // drop the empty reply
    messages.push({ role: "assistant", content: `(no answer: ${(e as Error).message})` });
    void checkModel();
  } finally {
    busy = false;
    render();
    input.focus();
  }
}

export function initChat(): void {
  $("chat-form").addEventListener("submit", (ev) => void submit(ev));
  $("chat-input").addEventListener("keydown", (ev) => {
    if (ev.key === "Enter" && !ev.shiftKey) {
      ev.preventDefault();
      $<HTMLFormElement>("chat-form").requestSubmit();
    }
  });
  $("chat-clear").onclick = () => {
    if (busy) return;
    messages = [];
    render();
  };
  setStatus("checking…", "busy");
  void checkModel();
  render();
}
